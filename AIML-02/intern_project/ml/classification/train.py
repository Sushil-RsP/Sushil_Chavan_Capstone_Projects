#!/usr/bin/env python3
"""
DenseNet121 training script for NIH ChestX-ray14 multi-label classification.

Usage:
    python ml/classification/train.py \
        --config configs/classification.yaml \
        --data-dir data/raw/nih_chestxray14 \
        --manifest-dir data/splits \
        --output-dir models/classification

Requirements:
    - NIH ChestX-ray14 dataset downloaded and extracted
    - Manifests generated by scripts/create_manifests.py
    - Python 3.11, PyTorch >= 2.0, torchvision >= 0.15

Hardware:
    - CPU: Extremely slow, not recommended for full training
    - GPU: 8+ GB VRAM recommended
    - Estimated time: 6-12 hours on a single GPU for 50 epochs

NOTE: This script trains a real model. Results depend on the dataset
and hardware. No results are fabricated or guaranteed.
"""
from __future__ import annotations
import argparse
import json
import logging
import os
import random
import time
from pathlib import Path

import numpy as np
import torch
import torch.nn as nn
from torch.utils.data import DataLoader, Dataset
from torchvision import models, transforms
import yaml
from PIL import Image
import csv

logging.basicConfig(level=logging.INFO, format="%(asctime)s %(levelname)s %(message)s")
logger = logging.getLogger(__name__)

LABELS = [
    "Atelectasis","Cardiomegaly","Consolidation","Edema","Effusion",
    "Emphysema","Fibrosis","Hernia","Infiltration","Mass",
    "No Finding","Nodule","Pleural_Thickening","Pneumonia","Pneumothorax",
]


def set_seed(seed: int) -> None:
    random.seed(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)
    if torch.cuda.is_available():
        torch.cuda.manual_seed_all(seed)


class ChestXRayDataset(Dataset):
    def __init__(self, manifest_path: Path, transform=None) -> None:
        self.records: list[dict] = []
        self.transform = transform
        with open(manifest_path, newline="") as f:
            reader = csv.DictReader(f)
            for row in reader:
                self.records.append(row)

    def __len__(self) -> int:
        return len(self.records)

    def __getitem__(self, idx: int):
        row = self.records[idx]
        img_path = Path(row["image_path"])
        try:
            img = Image.open(img_path).convert("RGB")
        except FileNotFoundError:
            raise FileNotFoundError(
                f"Image not found: {img_path}. "
                "Please download the NIH ChestX-ray14 dataset first."
            )
        if self.transform:
            img = self.transform(img)
        label_vec = torch.tensor(
            [int(row[lbl]) for lbl in LABELS], dtype=torch.float32
        )
        return img, label_vec


def build_model(num_classes: int, pretrained: bool = True) -> nn.Module:
    weights = models.DenseNet121_Weights.IMAGENET1K_V1 if pretrained else None
    model = models.densenet121(weights=weights)
    in_features = model.classifier.in_features
    model.classifier = nn.Linear(in_features, num_classes)
    return model


def train_epoch(
    model: nn.Module,
    loader: DataLoader,
    optimizer: torch.optim.Optimizer,
    criterion: nn.Module,
    device: torch.device,
    scaler=None,
) -> float:
    model.train()
    total_loss = 0.0
    for imgs, labels in loader:
        imgs, labels = imgs.to(device), labels.to(device)
        optimizer.zero_grad()
        if scaler:
            with torch.autocast(device_type=device.type):
                logits = model(imgs)
                loss = criterion(logits, labels)
            scaler.scale(loss).backward()
            scaler.step(optimizer)
            scaler.update()
        else:
            logits = model(imgs)
            loss = criterion(logits, labels)
            loss.backward()
            optimizer.step()
        total_loss += loss.item() * imgs.size(0)
    return total_loss / len(loader.dataset)


@torch.no_grad()
def evaluate(
    model: nn.Module, loader: DataLoader, criterion: nn.Module, device: torch.device
) -> tuple[float, np.ndarray, np.ndarray]:
    model.eval()
    total_loss = 0.0
    all_scores, all_labels = [], []
    for imgs, labels in loader:
        imgs, labels = imgs.to(device), labels.to(device)
        logits = model(imgs)
        loss = criterion(logits, labels)
        total_loss += loss.item() * imgs.size(0)
        all_scores.append(torch.sigmoid(logits).cpu().numpy())
        all_labels.append(labels.cpu().numpy())
    scores = np.concatenate(all_scores)
    labels = np.concatenate(all_labels)
    return total_loss / len(loader.dataset), scores, labels


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--config", default="configs/classification.yaml", type=Path)
    parser.add_argument("--data-dir", default="data/raw/nih_chestxray14", type=Path)
    parser.add_argument("--manifest-dir", default="data/splits", type=Path)
    parser.add_argument("--output-dir", default="models/classification", type=Path)
    parser.add_argument("--device", default="auto")
    parser.add_argument("--epochs", type=int, default=None)
    args = parser.parse_args()

    with open(args.config) as f:
        cfg = yaml.safe_load(f)

    set_seed(cfg["training"]["seed"])
    if args.device == "auto":
        device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    else:
        device = torch.device(args.device)
    logger.info("Using device: %s", device)

    epochs = args.epochs or cfg["training"]["epochs"]
    output_dir = args.output_dir
    output_dir.mkdir(parents=True, exist_ok=True)

    train_tf = transforms.Compose([
        transforms.Resize(256),
        transforms.RandomCrop(224),
        transforms.RandomHorizontalFlip(),
        transforms.ColorJitter(brightness=0.1, contrast=0.1),
        transforms.ToTensor(),
        transforms.Normalize([0.485,0.456,0.406],[0.229,0.224,0.225]),
    ])
    val_tf = transforms.Compose([
        transforms.Resize(256),
        transforms.CenterCrop(224),
        transforms.ToTensor(),
        transforms.Normalize([0.485,0.456,0.406],[0.229,0.224,0.225]),
    ])

    train_ds = ChestXRayDataset(args.manifest_dir / "train_manifest.csv", transform=train_tf)
    val_ds   = ChestXRayDataset(args.manifest_dir / "val_manifest.csv",   transform=val_tf)
    train_loader = DataLoader(train_ds, batch_size=cfg["training"]["batch_size"], shuffle=True,  num_workers=4, pin_memory=True)
    val_loader   = DataLoader(val_ds,   batch_size=cfg["training"]["batch_size"], shuffle=False, num_workers=4, pin_memory=True)

    model = build_model(num_classes=len(LABELS)).to(device)
    optimizer = torch.optim.Adam(
        model.parameters(),
        lr=cfg["training"]["learning_rate"],
        weight_decay=cfg["training"]["weight_decay"],
    )
    scheduler = torch.optim.lr_scheduler.CosineAnnealingLR(optimizer, T_max=epochs)
    criterion = nn.BCEWithLogitsLoss()
    scaler = torch.cuda.amp.GradScaler() if device.type == "cuda" else None

    best_val_loss = float("inf")
    patience_counter = 0
    patience = cfg["training"]["early_stopping_patience"]

    for epoch in range(1, epochs + 1):
        t0 = time.time()
        train_loss = train_epoch(model, train_loader, optimizer, criterion, device, scaler)
        val_loss, _, _ = evaluate(model, val_loader, criterion, device)
        scheduler.step()
        elapsed = time.time() - t0
        logger.info(
            "Epoch %d/%d | train_loss=%.4f | val_loss=%.4f | %.1fs",
            epoch, epochs, train_loss, val_loss, elapsed
        )

        if val_loss < best_val_loss:
            best_val_loss = val_loss
            patience_counter = 0
            ckpt = output_dir / "best_checkpoint.pth"
            torch.save({
                "epoch": epoch,
                "model_state_dict": model.state_dict(),
                "optimizer_state_dict": optimizer.state_dict(),
                "val_loss": val_loss,
                "labels": LABELS,
                "config": cfg,
            }, ckpt)
            logger.info("Saved best checkpoint to %s (val_loss=%.4f)", ckpt, val_loss)
        else:
            patience_counter += 1
            if patience_counter >= patience:
                logger.info("Early stopping at epoch %d", epoch)
                break

    logger.info("Training complete. Best val_loss=%.4f", best_val_loss)


if __name__ == "__main__":
    main()
